def stable_fraction(seed, *parts):
    payload = ":".join([str(seed), *(str(part) for part in parts)]).encode()
    return int.from_bytes(hashlib.sha256(payload).digest()[:8], "big") / 2**64


def weighted_status(value, weights):
    total = 0
    for status_value, weight in weights:
        total += weight
        if value < total:
            return status_value
    return weights[-1][0]


def shift_year(value, years):
    try:
        return value.replace(year=value.year + years)
    except ValueError:
        return value.replace(year=value.year + years, day=28)


def date_for_age(age, reference_date, rng):
    first = shift_year(reference_date, -(age + 1)) + timedelta(days=1)
    last = shift_year(reference_date, -age)
    return first + timedelta(days=rng.randrange((last - first).days + 1))


def elapsed_sundays(year, through_date):
    cursor = date(year, 1, 1)
    cursor += timedelta(days=(6 - cursor.weekday()) % 7)
    last = min(through_date, date(year, 12, 31))
    while cursor <= last:
        yield cursor
        cursor += timedelta(days=7)


def aware_at(day, clock, minute_offset=0):
    value = datetime.combine(day, clock) + timedelta(minutes=minute_offset)
    return timezone.make_aware(value, timezone.get_current_timezone())


class Command(BaseCommand):
    help = "Create deterministic development/demo data for Watoto Ministries DownTown."

    def add_arguments(self, parser):
        parser.add_argument("--children-per-group", type=int, default=45)
        parser.add_argument("--year", type=int, default=timezone.localdate().year)
        parser.add_argument("--through-date", default=timezone.localdate().isoformat(), help="Inclusive YYYY-MM-DD limit; future Sundays are not generated by default.")
        parser.add_argument("--password", default=DEFAULT_PASSWORD)
        parser.add_argument("--admin-email", default=DEFAULT_ADMIN_EMAIL)
        parser.add_argument("--admin-password", default=DEFAULT_PASSWORD)
        parser.add_argument("--seed", type=int, default=2026)

    def handle(self, *args, **options):
        children_per_group = options["children_per_group"]
        if not 40 <= children_per_group <= 50:
            raise CommandError("--children-per-group must be between 40 and 50.")
        try:
            through_date = date.fromisoformat(options["through_date"])
        except ValueError as exc:
            raise CommandError("--through-date must use YYYY-MM-DD format.") from exc
        through_date = min(through_date, timezone.localdate())
        if options["year"] < 2000 or options["year"] > 2100:
            raise CommandError("--year must be between 2000 and 2100.")

        self.stdout.write(self.style.WARNING("Creating DEVELOPMENT/DEMO sample data. Do not use the shared password in production."))
        with transaction.atomic():
            organization, branch = self._organization_and_branch()
            self._ensure_permission_catalog()
            age_groups = self._age_groups(organization, branch)
            administrator = self._administrator(
                organization, branch, options["admin_email"], options["admin_password"]
            )
            role = self._facilitator_role(organization)
            facilitators = self._facilitators(organization, branch, age_groups, role, options["password"])
            children = self._children(
                organization, branch, age_groups, children_per_group,
                options["seed"], options["year"],
            )
            counts = self._sundays(
                organization, branch, children, facilitators,
                options["year"], through_date, options["seed"],
            )

        self.stdout.write(self.style.SUCCESS(
            f"Watoto sample data ready: {len(children)} children, {len(facilitators)} facilitators, "
            f"{counts['events']} Sundays, {counts['sessions']} sessions, "
            f"{counts['child_attendance']} child attendance records and "
            f"{counts['facilitator_attendance']} facilitator attendance records."
        ))
        self.stdout.write(
            f"Administrator login: {administrator.email} / {options['admin_password']} "
            "(development/demo only)"
        )
        self.stdout.write(f"Facilitator login password: {options['password']} (development/demo only)")

    def _ensure_permission_catalog(self):
        """Make the demo administrator useful even on a fresh database."""
        permission_map = {**CORE_PERMISSIONS}
        for resource_code, actions in CHURCH_PERMISSIONS.items():
            permission_map[resource_code] = sorted(
                set(permission_map.get(resource_code, [])) | set(actions)
            )
        # Management permissions are intentionally absent from the facilitator
        # map but must exist for the administrator role.
        for resource_code in ("church-children", "church-age-groups", "church-facilitators"):
            permission_map[resource_code] = sorted(
                set(permission_map.get(resource_code, [])) | {"read", "manage"}
            )
        for resource_code, actions in permission_map.items():
            resource, _ = Resource.objects.update_or_create(
                code=resource_code,
                defaults={"name": resource_code.replace("-", " ").title(), "is_active": True},
            )
            for action in actions:
                AccessPermission.objects.update_or_create(
                    resource=resource,
                    action=action,
                    defaults={"codename": f"{resource_code}.{action}", "is_active": True},
                )

