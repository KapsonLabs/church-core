    def _children(self, organization, branch, age_groups, per_group, seed, year):
        reference_date = timezone.localdate()
        rng = random.Random(seed)
        children = []
        global_index = 0
        for group in age_groups:
            for group_index in range(per_group):
                global_index += 1
                first_name = UGANDAN_FIRST_NAMES[(global_index * 7 + group_index) % len(UGANDAN_FIRST_NAMES)]
                last_name = UGANDAN_SURNAMES[(global_index * 11 + group.minimum_age) % len(UGANDAN_SURNAMES)]
                guardian_first = UGANDAN_FIRST_NAMES[(global_index * 13) % len(UGANDAN_FIRST_NAMES)]
                guardian_last = UGANDAN_SURNAMES[(global_index * 17) % len(UGANDAN_SURNAMES)]
                contact = f"+256700{global_index:06d}"
                child, _ = Child.objects.update_or_create(
                    branch=branch,
                    guardian_contact=contact,
                    defaults={
                        "organization": organization,
                        "first_name": first_name,
                        "last_name": last_name,
                        "other_names": "",
                        "date_of_birth": date_for_age(group.minimum_age, reference_date, rng),
                        "age_group": group,
                        "guardian_name": f"{guardian_first} {guardian_last}",
                        "location": KAMPALA_LOCATIONS[(global_index - 1) % len(KAMPALA_LOCATIONS)],
                        "registration_date": date(year, 1, 1),
                        "is_active": True,
                    },
                )
                children.append(child)
        return children

    def _sundays(self, organization, branch, children, facilitators, year, through_date, seed):
        actor = facilitators[0].user
        sunday_dates = list(elapsed_sundays(year, through_date))
        for sunday in sunday_dates:
            event, _ = Event.objects.update_or_create(
                branch=branch,
                event_date=sunday,
                event_type=Event.Type.SUNDAY_SERVICE,
                defaults={
                    "organization": organization,
                    "name": f"Sunday Service, {sunday:%d %B %Y}",
                    "description": "Generated Watoto Ministries demo Sunday service.",
                    "location": BRANCH_NAME,
                    "status": Event.Status.COMPLETED,
                    "created_by": actor,
                },
            )
            sessions = []
            for order, (name, starts, ends) in enumerate(SESSION_DEFINITIONS, 1):
                session, _ = ServiceSession.objects.update_or_create(
                    event=event,
                    service_order=order,
                    defaults={
                        "name": name, "start_time": starts, "end_time": ends,
                        "location": BRANCH_NAME, "status": Event.Status.COMPLETED,
                    },
                )
                sessions.append(session)
                for facilitator in facilitators[(order - 1) * 3:order * 3]:
                    ServiceFacilitator.objects.update_or_create(
                        service_session=session,
                        facilitator=facilitator,
                        defaults={
                            "role": ServiceFacilitator.Role.LEAD if facilitator == facilitators[(order - 1) * 3] else ServiceFacilitator.Role.TEACHER,
                            "assigned_by": actor,
                        },
                    )
            self._child_attendance(event, sessions, children, actor, seed)
            self._facilitator_attendance(event, sessions, facilitators, actor, seed)
            finalize_sunday_attendance(event, actor)
            event.attendance_finalized_at = aware_at(sunday, time(17, 0))
            event.attendance_finalized_by = actor
            event.status = Event.Status.COMPLETED
            event.save(update_fields=["attendance_finalized_at", "attendance_finalized_by", "status", "updated_at"])

        return {
            "events": Event.objects.filter(branch=branch, event_type=Event.Type.SUNDAY_SERVICE, event_date__in=sunday_dates).count(),
            "sessions": ServiceSession.objects.filter(event__branch=branch, event__event_date__in=sunday_dates).count(),
            "child_attendance": ChildAttendance.objects.filter(event__branch=branch, event__event_date__in=sunday_dates).count(),
            "facilitator_attendance": FacilitatorAttendance.objects.filter(service_session__event__branch=branch, service_session__event__event_date__in=sunday_dates).count(),
        }

    def _child_attendance(self, event, sessions, children, actor, seed):
        existing = {
            (record.child_id, record.service_session_id): record
            for record in ChildAttendance.objects.filter(event=event, service_session__isnull=False)
        }
        creates = []
        updates = []
        for index, child in enumerate(children):
            value = stable_fraction(seed, "child", event.event_date, child.guardian_contact)
            status_value = weighted_status(value, [
                (AttendanceStatus.PRESENT, .82), (AttendanceStatus.LATE, .05),
                (AttendanceStatus.EXCUSED, .04), (AttendanceStatus.ABSENT, .09),
            ])
            if status_value == AttendanceStatus.ABSENT:
                continue
            session = sessions[index % len(sessions)]
            minute_offset = int(stable_fraction(seed, "checkin", event.event_date, child.guardian_contact) * 12)
            if status_value == AttendanceStatus.LATE:
                minute_offset += 15
            checked_in_at = aware_at(event.event_date, session.start_time, minute_offset) if status_value in [AttendanceStatus.PRESENT, AttendanceStatus.LATE] else None
            record = existing.get((child.id, session.id))
            if record:
                record.age_group = child.age_group
                record.attendance_status = status_value
                record.checked_in_at = checked_in_at
                record.recorded_by = actor
                record.notes = "Generated Watoto Ministries demo attendance."
                updates.append(record)
            else:
                creates.append(ChildAttendance(
                    child=child, event=event, service_session=session, age_group=child.age_group,
                    attendance_status=status_value, checked_in_at=checked_in_at,
                    recorded_by=actor, notes="Generated Watoto Ministries demo attendance.",
                ))
        ChildAttendance.objects.bulk_create(creates)
        if updates:
            ChildAttendance.objects.bulk_update(updates, ["age_group", "attendance_status", "checked_in_at", "recorded_by", "notes", "updated_at"])

    def _facilitator_attendance(self, event, sessions, facilitators, actor, seed):
        existing = {
            (record.service_session_id, record.facilitator_id): record
            for record in FacilitatorAttendance.objects.filter(service_session__event=event)
        }
        creates = []
        updates = []
        for session_index, session in enumerate(sessions):
            for facilitator in facilitators[session_index * 3:(session_index + 1) * 3]:
                value = stable_fraction(seed, "facilitator", event.event_date, facilitator.user.email)
                status_value = weighted_status(value, [
                    (AttendanceStatus.PRESENT, .90), (AttendanceStatus.LATE, .05),
                    (AttendanceStatus.EXCUSED, .03), (AttendanceStatus.ABSENT, .02),
                ])
                minute_offset = int(stable_fraction(seed, "facilitator-checkin", event.event_date, facilitator.user.email) * 10)
                if status_value == AttendanceStatus.LATE:
                    minute_offset += 15
                checked_in_at = aware_at(event.event_date, session.start_time, minute_offset) if status_value in [AttendanceStatus.PRESENT, AttendanceStatus.LATE] else None
                record = existing.get((session.id, facilitator.id))
                if record:
                    record.attendance_status = status_value
                    record.checked_in_at = checked_in_at
                    record.recorded_by = actor
                    record.notes = "Generated Watoto Ministries demo facilitator attendance."
                    updates.append(record)
                else:
                    creates.append(FacilitatorAttendance(
                        service_session=session, facilitator=facilitator,
                        attendance_status=status_value, checked_in_at=checked_in_at,
                        recorded_by=actor, notes="Generated Watoto Ministries demo facilitator attendance.",
                    ))
        FacilitatorAttendance.objects.bulk_create(creates)
        if updates:
            FacilitatorAttendance.objects.bulk_update(updates, ["attendance_status", "checked_in_at", "recorded_by", "notes", "updated_at"])
